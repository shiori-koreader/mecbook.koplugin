local expiry = require("loans.expiry")

describe("expiry.parse_iso", function()
    it("parses UTC", function()
        assert.equals(0, expiry.parse_iso("1970-01-01T00:00:00Z"))
        assert.equals(1793594160, expiry.parse_iso("2026-11-02T04:36:00Z"))
    end)
    it("applies the offset", function()
        assert.equals(expiry.parse_iso("2026-11-02T12:00:00Z"), expiry.parse_iso("2026-11-02T09:00:00-03:00"))
    end)
    it("accepts fractional seconds and date only", function()
        assert.equals(expiry.parse_iso("2026-11-02T12:00:00Z"), expiry.parse_iso("2026-11-02T12:00:00.123Z"))
        assert.equals(expiry.parse_iso("2026-11-02T00:00:00Z"), expiry.parse_iso("2026-11-02"))
    end)
    it("handles leap days", function()
        assert.equals(86400, expiry.parse_iso("2024-03-01T00:00:00Z") - expiry.parse_iso("2024-02-29T00:00:00Z"))
    end)
    it("rejects garbage", function()
        assert.is_nil(expiry.parse_iso("tomorrow"))
        assert.is_nil(expiry.parse_iso(nil))
    end)
end)

describe("expiry.days_left", function()
    it("rounds up and never goes negative", function()
        assert.equals(1, expiry.days_left(100, 0))
        assert.equals(2, expiry.days_left(86401, 0))
        assert.equals(0, expiry.days_left(100, 200))
    end)
end)
